    function renderSleepTimes(data) {
      if (!data || !data.sleep) { sleepTimes.textContent = '--'; return; }
      const s = data.sleep;
      const idle = Number(s.idle24gSeconds ?? 0);
      const deep = Number(s.deep24gSeconds ?? 0);
      if (idle <= 0 && deep <= 0) {
        sleepTimes.textContent = '--';
        return;
