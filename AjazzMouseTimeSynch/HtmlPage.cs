    function createWireframe(canvas) {
      const ctx = canvas.getContext('2d');
      const dpr = Math.max(1, Math.min(window.devicePixelRatio || 1, 2));
      const step = 56;
      const influenceRadius = 200;
      const points = [];
      const mouse = { x: -10000, y: -10000 };
      let width = 0;
      let height = 0;

      function resize() {
        width = window.innerWidth;
        height = window.innerHeight;

        canvas.width = Math.floor(width * dpr);
        canvas.height = Math.floor(height * dpr);
        canvas.style.width = `${width}px`;
        canvas.style.height = `${height}px`;

        ctx.setTransform(dpr, 0, 0, dpr, 0, 0);

        points.length = 0;
        for (let y = 0; y <= height + step; y += step) {
          for (let x = 0; x <= width + step; x += step) {
            points.push({
              x,
              y,
              baseX: x,
              baseY: y,
              drift: Math.random() * Math.PI * 2,
              speed: 0.4 + Math.random() * 0.9
            });
          }
        }
      }

      function draw(timeMs) {
        const t = timeMs * 0.001;
        ctx.clearRect(0, 0, width, height);

        ctx.lineWidth = 1;
        for (const p of points) {
          const dx = mouse.x - p.baseX;
          const dy = mouse.y - p.baseY;
          const dist = Math.hypot(dx, dy);
          const push = Math.max(0, 1 - dist / influenceRadius);

          const wobbleX = Math.sin(t * p.speed + p.drift) * 5;
          const wobbleY = Math.cos(t * p.speed + p.drift) * 5;
          const repelX = dist > 0 ? -(dx / dist) * push * 16 : 0;
          const repelY = dist > 0 ? -(dy / dist) * push * 16 : 0;

          p.x = p.baseX + wobbleX + repelX;
          p.y = p.baseY + wobbleY + repelY;
        }

        const cols = Math.floor(width / step) + 2;
        const rows = Math.floor(height / step) + 2;

        for (let r = 0; r < rows; r++) {
          for (let c = 0; c < cols; c++) {
            const i = r * cols + c;
            const p = points[i];
            if (!p) continue;

            const right = points[i + 1];
            const down = points[i + cols];

            if (right) {
              const alpha = Math.max(0.08, 0.3 - Math.abs(mouse.x - (p.x + right.x) * 0.5) / 1800);
