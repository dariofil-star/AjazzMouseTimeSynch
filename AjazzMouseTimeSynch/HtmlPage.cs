          const dist = Math.hypot(dx, dy);
          const push = Math.max(0, 1 - dist / influenceRadius);

          const wobbleX = Math.sin(t * p.speed + p.drift) * 5;
          const wobbleY = Math.cos(t * p.speed + p.drift) * 5;
          const repelX = dist > 0 ? -(dx / dist) * push * 16 : 0;
          const repelY = dist > 0 ? -(dy / dist) * push * 16 : 0;

          p.x = p.baseX + wobbleX + repelX;
          p.y = p.baseY + wobbleY + repelY;
        }

        const cols = Math.floor(width / step) + 2;
        const rows = Math.floor(height / step) + 2;

        for (let r = 0; r < rows; r++) {
          for (let c = 0; c < cols; c++) {
            const i = r * cols + c;
            const p = points[i];
            if (!p) continue;

            const right = points[i + 1];
            const down = points[i + cols];

            if (right) {
              const alpha = Math.max(0.08, 0.3 - Math.abs(mouse.x - (p.x + right.x) * 0.5) / 1800);
              ctx.strokeStyle = `rgba(110, 186, 255, ${alpha})`;
              ctx.beginPath();
              ctx.moveTo(p.x, p.y);
              ctx.lineTo(right.x, right.y);
              ctx.stroke();
            }

            if (down) {
              const alpha = Math.max(0.06, 0.24 - Math.abs(mouse.y - (p.y + down.y) * 0.5) / 1700);
              ctx.strokeStyle = `rgba(61, 239, 186, ${alpha})`;
              ctx.beginPath();
              ctx.moveTo(p.x, p.y);
              ctx.lineTo(down.x, down.y);
              ctx.stroke();
            }
          }
        }

        ctx.fillStyle = 'rgba(145, 223, 255, 0.26)';
        for (const p of points) {
          ctx.fillRect(p.x - 0.5, p.y - 0.5, 1.25, 1.25);
        }

        requestAnimationFrame(draw);
      }

      window.addEventListener('mousemove', (e) => {
        mouse.x = e.clientX;
        mouse.y = e.clientY;
      }, { passive: true });

      window.addEventListener('mouseleave', () => {
        mouse.x = -10000;
        mouse.y = -10000;
      });

      window.addEventListener('touchmove', (e) => {
        if (!e.touches || e.touches.length === 0) return;
        mouse.x = e.touches[0].clientX;
        mouse.y = e.touches[0].clientY;
      }, { passive: true });

      window.addEventListener('touchend', () => {
        mouse.x = -10000;
        mouse.y = -10000;
      }, { passive: true });

      window.addEventListener('resize', resize, { passive: true });

      resize();
      requestAnimationFrame(draw);
      return { resize };
    }

